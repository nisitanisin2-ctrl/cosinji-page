/* 入力中の数字の桁の読み（例 5000000 → 500万）の固定テスト。
   4桁以下・文字・数式では出さない、という線引きと、
   兆を超えても桁がずれないことを毎回確かめる。 */
'use strict';

/* [入れるもの, 期待する表示]。'' ＝ 出さない */
const CASES = [
  ['5000000',   '500万'],
  ['50000',     '5万'],
  ['10000',     '1万'],
  ['12345678',  '1234万5678'],
  ['100000000', '1億'],
  ['1250000',   '125万'],
  ['-3000000',  '-300万'],
  ['12345.6',   '1万2345.6'],
  ['5,000,000', '500万'],              // カンマ付きで入れても読める
  ['9999',      ''],                   // 4桁以下は出さない
  ['0',         ''],
  ['999',       ''],
  ['りんご',     ''],                   // 文字は出さない
  ['=A1*3',     ''],                   // 数式そのものは出さない
  ['',          ''],
  ['12px',      ''],
];

/* 兆を超えても桁がずれないこと（数にすると 9007兆 あたりから狂っていた） */
const BIG = [
  ['1000000000000',          '1兆'],
  ['1000000000001',          '1兆1'],
  ['20000000000000',         '20兆'],
  ['1234567890123',          '1兆2345億6789万123'],
  ['1000000000000.5',        '1兆0.5'],
  ['123456789012345678',     '12京3456兆7890億1234万5678'],
  ['99999999999999999999',   '9999京9999兆9999億9999万9999'],
  ['1234567890123456789012', '12垓3456京7890兆1234億5678万9012'],
  // 垓より上は漢数字にせず、数字のまま出す（間違った読みを出さない）
  ['1000000000000000000000000', '1,000,000,000,000,000,000,000,000'],
];

/* テンキーで打っている途中も、桁が増えたところで出る */
const TYPING = { keys: ['n5','n0','n0','n0','n0','n0','n0'],
                 expect: ['', '', '', '', '5万', '50万', '500万'] };

/* 数式のセルは、計算結果の桁を出す */
const FORMULA = { setup: [[0,0,'5000000'],[1,0,'=A1*3']], at: [1,0], want: '1500万' };

module.exports = { CASES, BIG, TYPING, FORMULA };
