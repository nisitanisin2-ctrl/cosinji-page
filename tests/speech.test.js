/* しゃべった式の読み取りの固定テスト。
   音声入力で入る文字は端末によって形が違うので、どの言い方でも同じ式になること、
   そして「式ではない言葉」を式にしてしまわないことを毎回確かめる。 */
'use strict';

/* [言った（入った）文字, 期待する式]。'' ＝ 文字のまま入れる */
const CASES = [
  // 記号で入るとき
  ['251×68',                 '=251*68'],
  ['251*68',                 '=251*68'],
  ['100÷4',                  '=100/4'],
  ['２５１×６８',               '=251*68'],          // 全角
  // ことばで入るとき
  ['251かける68',             '=251*68'],
  ['251掛ける68',             '=251*68'],
  ['100わる4',                '=100/4'],
  ['1200たす350',             '=1200+350'],
  ['1200足す350ひく200',       '=1200+350-200'],
  ['500プラス20',             '=500+20'],
  ['500マイナス20',           '=500-20'],
  ['２５１ かける ６８ は',       '=251*68'],          // 空白と「は」
  ['251かける68は？',          '=251*68'],
  ['計算して 20かける3',        '=20*3'],            // 前置きも落とす
  ['20かける3を計算して',       '=20*3'],
  // 漢数字
  ['二百五十一かける六十八',      '=251*68'],
  ['一万二千三百たす500',        '=12300+500'],
  ['十かける十',               '=10*10'],
  // 小数・かっこ
  ['3てん5かける2',            '=3.5*2'],
  ['かっこ100たす20かっことじかける3', '=(100+20)*3'],
  ['かっこ100たす20閉じかっこわる4',  '=(100+20)/4'],

  // ここから下は「式にしない」もの
  ['みかん3個',               ''],
  ['りんご',                  ''],
  ['こんにちは',              ''],
  ['251',                    ''],                  // ただの数字は式にしない
  ['50パーセント',            ''],                  // 計算するところが無い
  ['=251*68',                ''],                  // すでに数式＝触らない
  ['2かける',                 ''],                  // 言いかけ
  ['かける68',                ''],
  ['かっこ100たす20かける3',    ''],                  // かっこが合わない
  ['',                       ''],
];

module.exports = { CASES };
