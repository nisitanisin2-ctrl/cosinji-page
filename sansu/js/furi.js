/* ── 漢数字の よみ（一万・三千六百二十八 など） ── */
const KD = {〇: 0, 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9};
const DY = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];
function kanNum(run){
  let total = 0, sec = 0, dg = 0;
  for(const ch of run){
    if(ch in KD) dg = KD[ch];
    else if(ch === '十' || ch === '百' || ch === '千'){ sec += (dg || 1) * {十: 10, 百: 100, 千: 1000}[ch]; dg = 0; }
    else if(ch === '万'){ total += (sec + dg || 1) * 10000; sec = 0; dg = 0; }
  }
  return total + sec + dg;
}
function secYomi(n){
  const th = Math.floor(n / 1000) % 10, hu = Math.floor(n / 100) % 10, te = Math.floor(n / 10) % 10, on = n % 10;
  return (th ? {1: 'せん', 3: 'さんぜん', 8: 'はっせん'}[th] || DY[th] + 'せん' : '')
    + (hu ? {1: 'ひゃく', 3: 'さんびゃく', 6: 'ろっぴゃく', 8: 'はっぴゃく'}[hu] || DY[hu] + 'ひゃく' : '')
    + (te ? (te === 1 ? '' : DY[te]) + 'じゅう' : '') + DY[on];
}
const numYomi = run => { const n = kanNum(run), m = Math.floor(n / 10000), o = n % 10000; return n ? (m ? secYomi(m) + 'まん' : '') + secYomi(o) : 'ぜろ'; };

