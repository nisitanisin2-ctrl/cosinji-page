/* 字の 並びを [{t}（そのまま）か {k, r}（漢字と よみ）] に 分ける */
function split(s, afterBlank){
  const out = [], put = t => { const l = out[out.length - 1]; if(l && l.t != null) l.t += t; else out.push({t}); };
  let i = 0;
  while(i < s.length){
    const ch = s[i];
    // 数字の あとの 人・本・分・時
    if(/\d/.test(ch) && !/\d/.test(s[i - 1] || '')){
      const m = /(\d+)(人|本|分(?!の[\d一二三四五六七八九十])|時間|時)/y; m.lastIndex = i; const r = m.exec(s);   // 3分の1 の 分は ぶん
      if(r){ const n = r[1], d = n[n.length - 1], c = r[2];
        if(c === '人' && (n === '1' || n === '2')) out.push({k: n + '人', r: n === '1' ? 'ひとり' : 'ふたり'});
        else { put(n); out.push({k: c, r: c === '人' ? 'にん' : c === '本' ? HON(d) : c === '分' ? PUN(d) : c === '時間' ? 'じかん' : 'じ'}); }
        i += r[0].length; continue; }
    }
    if(!/[一-鿿々]/.test(ch)){ put(ch); i++; continue; }
    let hit = null;
    for(const [w, y] of WORDS){
      if(typeof w === 'string'){ if(s.startsWith(w, i)){ hit = [w, y]; break; } }
      else { w.lastIndex = i; const r = w.exec(s); if(r){ hit = [r[0], y]; break; } }
    }
    if(hit){ out.push({k: hit[0], r: hit[1]}); i += hit[0].length; continue; }
    const nr = /[一二三四五六七八九十百千万]+/y; nr.lastIndex = i; const nm = nr.exec(s);
    if(nm && !(nm[0] === '万' && /\d/.test(s[i - 1] || ''))){ out.push({k: nm[0], r: numYomi(nm[0])}); i += nm[0].length; continue; }
    const prev = s[i - 1] || '', next = s[i + 1] || '', lead = !!afterBlank && /^\s*$/.test(s.slice(0, i));   // lead：答えの □ の すぐ あと（「□ 人」「□分」）
    let y = ONE[ch];
    if(ch === '算') y = /[しきけりっ]/.test(prev) ? 'ざん' : 'さん';
    else if(ch === '後') y = prev === '分' ? 'ご' : 'あと';
    else if(ch === '車') y = prev === 'う' ? 'しゃ' : 'くるま';
    else if(ch === '分' && next === 'の') y = 'ぶん';
    else if(ch === '分' && lead) y = 'ふん';   // □分 は 時こくの 分
    else if(ch === '人' && lead) y = 'にん';   // □ 人 は 人数
    else if(ch === '間' && prev === '時') y = 'かん';
    if(y){ out.push({k: ch, r: y}); i++; continue; }
    put(ch); i++;
  }
  return out;
}
const esc = s => String(s).replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
/* テキストの 部分（エスケープずみ）だけを かえる */
function textPart(t, mode, afterBlank){
  if(!/[一-鿿々]/.test(t)) return t;
  return split(t, afterBlank).map(x => x.t != null ? x.t : mode === 'kana' ? esc(x.r) : `<ruby>${x.k}<rt>${esc(x.r)}</rt></ruby>`).join('');
}
S.furi = (html, mode) => {
  if(!html || (mode !== 'ruby' && mode !== 'kana')) return html;
  let svg = 0, prev = '';
  return String(html).split(/(<[^>]*>)/).map(p => {
    if(p[0] === '<'){ if(/^<svg[\s>]/i.test(p)) svg++; else if(/^<\/svg>/i.test(p)) svg = Math.max(0, svg - 1); prev = p; return p; }
    const out = svg && mode === 'ruby' ? p : textPart(p, mode, /^<\/(button|span|b)>$/i.test(prev));   // □（ボタン・わく）の すぐ あとの 分・人
    if(p) prev = '';
    return out;
  }).join('');
};
